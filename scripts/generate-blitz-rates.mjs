/**
 * Regenerates server/blitzRates.generated.ts — the sampled net-price tables the
 * automatic Blitz-Angebot estimate uses server-side.
 *
 * The server deliberately never imports from src/ (see server/i18n.ts), so the
 * haus/wohnung package catalogs are sampled here at build/authoring time
 * instead: for every package the DEFAULT configuration (enabled products,
 * Standard tier) is priced across an area grid with the exact quantity
 * semantics of useRenovationCalculator (formula evaluation, base-quantity
 * scaling, step rounding). Run after any calculator package/price change:
 *
 *   node scripts/generate-blitz-rates.mjs
 */
import { mkdtemp, rm, writeFile } from 'node:fs/promises';
import { tmpdir } from 'node:os';
import path from 'node:path';
import { pathToFileURL } from 'node:url';
import { build } from 'esbuild';

const ROOT = process.cwd();
const OUT_FILE = path.join(ROOT, 'server/blitzRates.generated.ts');

const AREA_MIN = 20;
const AREA_MAX = 400;
const AREA_STEP = 5;

const SERIES = [
  { id: '1e', group: 'haus', importFile: 'blitz-haus-3', exportName: 'packageBlitzHaus3' },
  { id: '1e-d', group: 'haus', importFile: 'blitz-haus-1', exportName: 'packageBlitzHaus1' },
  { id: '2e', group: 'haus', importFile: 'blitz-haus-4', exportName: 'packageBlitzHaus4' },
  { id: '2e-d', group: 'haus', importFile: 'blitz-haus-2', exportName: 'packageBlitzHaus2' },
  { id: 'studio', group: 'wohnung', importFile: 'wohnung-studio', exportName: 'packageWohnungStudio' },
  { id: '2zi', group: 'wohnung', importFile: 'wohnung-2zi', exportName: 'packageWohnung2zi' },
  { id: '3zi', group: 'wohnung', importFile: 'wohnung-3zi', exportName: 'packageWohnung3zi' },
  { id: 'maisonette', group: 'wohnung', importFile: 'wohnung-maisonette', exportName: 'packageWohnungMaisonette' },
];

const entry = [
  ...SERIES.map((s) => `import { ${s.exportName} } from './src/data/calculator/packages/${s.importFile}';`),
  "import { evaluateQuantityFormula } from './src/data/calculator/engine';",
  `export const packages = { ${SERIES.map((s) => `'${s.id}': ${s.exportName}`).join(', ')} };`,
  'export { evaluateQuantityFormula };',
].join('\n');

const bundle = await build({
  stdin: { contents: entry, resolveDir: ROOT, loader: 'ts' },
  bundle: true,
  platform: 'node',
  format: 'esm',
  write: false,
  logLevel: 'error',
});

const tmpDir = await mkdtemp(path.join(tmpdir(), 'blitz-rates-'));
const tmpFile = path.join(tmpDir, 'packages.mjs');
await writeFile(tmpFile, bundle.outputFiles[0].text);
const { packages, evaluateQuantityFormula } = await import(pathToFileURL(tmpFile).href);
await rm(tmpDir, { recursive: true, force: true });

// --- Quantity semantics mirrored from src/hooks/useRenovationCalculator.ts ---

function decimalPlaces(value) {
  const [, decimals = ''] = String(value).split('.');
  return decimals.length;
}

function roundQuantityToStep(value, step) {
  const safeStep = step > 0 ? step : 1;
  const precision = Math.max(decimalPlaces(safeStep), decimalPlaces(value));
  return Number((Math.round(value / safeStep) * safeStep).toFixed(precision));
}

function automaticQuantity(product, livingArea, floorCount, scaleBase) {
  if (product.scalable && product.formula) {
    const raw = evaluateQuantityFormula(product.formula, { livingArea, floorCount });
    if (raw === null) return product.baseQuantity;
    return Math.max(0, roundQuantityToStep(raw, product.quantityStep));
  }
  const scaled = product.baseQuantity * (livingArea / scaleBase);
  return Math.max(0, roundQuantityToStep(scaled, product.quantityStep));
}

function netAt(pkg, area) {
  const scaleBase = pkg.defaultArea > 0 ? pkg.defaultArea : 1;
  let net = 0;
  for (const category of pkg.categories) {
    for (const subsection of category.subsections) {
      for (const product of subsection.products) {
        if (!product.enabled) continue;
        net += automaticQuantity(product, area, pkg.defaultFloorCount, scaleBase) * product.basePrice;
      }
    }
  }
  return net;
}

const generatedSeries = SERIES.map((s) => {
  const pkg = packages[s.id];
  if (!pkg) throw new Error(`package ${s.id} not found`);
  const nets = [];
  for (let area = AREA_MIN; area <= AREA_MAX; area += AREA_STEP) {
    nets.push(Math.round(netAt(pkg, area)));
  }
  return {
    id: s.id,
    label: pkg.title ?? pkg.name ?? s.id,
    group: s.group,
    defaultArea: pkg.defaultArea,
    nets,
  };
});

const today = new Date().toISOString().slice(0, 10);
const lines = [
  '// AUTO-GENERATED by scripts/generate-blitz-rates.mjs — DO NOT EDIT BY HAND.',
  '// Net prices (EUR, Standard tier, default configuration) sampled from the',
  '// live calculator packages across an area grid. Regenerate after any',
  '// calculator package/price change:  node scripts/generate-blitz-rates.mjs',
  '',
  `export const BLITZ_RATES_GENERATED_AT = '${today}';`,
  '',
  `export const BLITZ_RATES_AREA_MIN = ${AREA_MIN};`,
  `export const BLITZ_RATES_AREA_MAX = ${AREA_MAX};`,
  `export const BLITZ_RATES_AREA_STEP = ${AREA_STEP};`,
  '',
  'export type BlitzRateSeries = {',
  '  id: string;',
  '  label: string;',
  "  group: 'haus' | 'wohnung';",
  '  defaultArea: number;',
  '  /** Net EUR at areas AREA_MIN, AREA_MIN+STEP, …, AREA_MAX. */',
  '  nets: readonly number[];',
  '};',
  '',
  'export const BLITZ_RATE_SERIES: readonly BlitzRateSeries[] = [',
  ...generatedSeries.map((s) => [
    '  {',
    `    id: '${s.id}',`,
    `    label: ${JSON.stringify(s.label)},`,
    `    group: '${s.group}',`,
    `    defaultArea: ${s.defaultArea},`,
    `    nets: [${s.nets.join(', ')}],`,
    '  },',
  ].join('\n')),
  '];',
  '',
];
await writeFile(OUT_FILE, lines.join('\n'));
console.log(`Wrote ${OUT_FILE}: ${generatedSeries.length} series × ${generatedSeries[0].nets.length} area points (${AREA_MIN}–${AREA_MAX} m², step ${AREA_STEP}).`);
